import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import vm from 'node:vm';
const read=name=>readFileSync(new URL(name,import.meta.url),'utf8');
const context=vm.createContext({});
vm.runInContext(read('data.js')+';globalThis.data=RESEARCH',context);
const data=context.data,ids=new Set(data.sources.map(s=>s.id));
assert.equal(ids.size,data.sources.length,'Source IDs must be unique');
assert.equal(data.vendors.length,10);
for(const s of data.sources){assert.equal(new URL(s.url).protocol,'https:');assert.ok(['verified','conflict','partial'].includes(s.status));assert.ok(s.evidence&&s.boundary);}
for(const v of data.vendors){
  assert.equal(v.cells.length,3);
  for(const f of [...v.cells.flat(),...v.extra]){assert.ok(f.refs.length);for(const id of f.refs)assert.ok(ids.has(id),`${v.name}: unknown source ${id}`);}
}
const app=read('app.js');
vm.runInContext(app.slice(app.indexOf('function ceilUnits('),app.indexOf('const inquiry=')),context);
const calc=(...args)=>context.estimateRates(...args);
assert.equal(calc(.2,10,10,5).haoku,900,'Minimum first weight');
assert.equal(calc(.5,10,10,5).haoku,900);
assert.equal(calc(.5,10,10,5).exactBoundary,true,'0.50kg ambiguity is disclosed');
assert.equal(calc(.6,10,10,5).haoku,1080);
assert.equal(calc(4.2,40,30,20).haoku,7560);
assert.equal(calc(4.2,40,30,20).qihang,10000);
assert.equal(calc(4.21,40,30,20).haoku,7740);
assert.equal(calc(4,60,26,20).volumeTriggered,false,'Exactly 1.3x does not trigger');
assert.equal(calc(4,60,26.1,20).volumeTriggered,true);
assert.equal(calc(3,60,30,20).surcharge,900,'Volumetric difference rounded up');
assert.equal(calc(3,60,30,20).haoku,6300);
assert.equal(calc(3,60,30,20).qihang,12000);
assert.equal(calc(20,10,10,10).qihang,40000);
assert.equal(calc(20.01,10,10,10).qihang,null,'Stop over regular weight');
assert.equal(calc(1,100,100,100).qihang,null,'Stop over volumetric weight');
assert.equal(calc(20.01,10,10,10).haoku,null,'Stop over tool model range');
for(const w of [0,-1,NaN,Infinity])assert.ok(calc(w,10,10,10).error);
assert.ok(calc(101,10,10,10).error);
assert.ok(calc(1,301,10,10).error);
const quote=(id,mode,overrides={})=>context.getQuote(id,mode,{weight:5,packages:10,fx:4.5,...overrides});
assert.equal(quote('cosmos','air').min,6100);
assert.equal(quote('cosmos','sea').min,4650);
assert.equal(quote('transbang','air').min,5100);
assert.equal(quote('transbang','sea').min,3650);
assert.equal(quote('transbang','air',{weight:4.2}).min,5060,'Service fee uses actual weight');
assert.equal(quote('transbang','air',{weight:3,length:60,width:30,height:20}).min,3600,'Postal rate does not inherit CC dimensional surcharge');
assert.equal(quote('jgs','air').min,5050);
assert.equal(quote('jgs','sea').min,3600);
assert.equal(quote('jgs','air',{packages:11}).min,5170);
assert.equal(quote('jgs','air',{packages:2,weight:3}).min,3317.5,'Conditional two-parcel air discount');
assert.equal(quote('jpgoodbuy','air').min,5600);
assert.equal(quote('jpgoodbuy','sea').min,4150,'Use current displayed fee, add only known consolidation');
assert.equal(quote('xiaojuanmao','air').min,5150,'Mainland tier 1 air tariff at 5kg');
assert.equal(quote('xiaojuanmao','sea').min,4000,'Mainland tier 1 sea tariff at 5kg');
assert.equal(quote('xiaojuanmao','air',{weight:3}).min,3650);
assert.equal(quote('xiaojuanmao','sea',{weight:3}).min,3200);
assert.equal(quote('xiaojuanmao','air',{weight:.4}).status,'unknown','Official air/sea table starts at 0.5kg');
assert.equal(quote('xiaojuanmao','air',{packages:11}).min,5250,'One known over-10 consolidation fee');
assert.equal(quote('transportjp','air').min,4645);
assert.equal(quote('transportjp','air').max,4850);
assert.equal(quote('transportjp','air').sortEligible,false);
assert.equal(quote('transportjp','air',{packages:16}).status,'unknown');
assert.equal(quote('haoku','air').min,9000);
assert.equal(quote('haoku','air').max,9180);
assert.equal(quote('haoku','air',{packages:16}).status,'unknown');
assert.equal(quote('haoku','air',{weight:15}).status,'unknown','Respect 14.5kg consolidation cap');
assert.equal(quote('transportjp','air',{weight:.5}).status,'unknown','Conflicting minimum charge needs confirmation');
assert.equal(quote('qihang','air').min,10000);
assert.equal(quote('qihang','sea').status,'unknown');
assert.equal(quote('sf518','air').status,'ineligible');
assert.equal(quote('shunxing','air').status,'unknown','No single verified flat rate without route and dimensions');
assert.equal(data.report.rows.length,10);
for(const row of data.report.rows)for(const ref of row.refs)assert.ok(ids.has(ref));
const html=read('index.html');
const htmlIds=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(htmlIds.length,new Set(htmlIds).size,'Unique HTML IDs');
for(const match of app.matchAll(/\$\('([^']+)'\)/g))assert.ok(htmlIds.includes(match[1]),`DOM target missing: ${match[1]}`);
for(const match of html.matchAll(/(?:src|href)="((?:styles\.css|app\.js|data\.js))(?:\?[^"\s]*)?"/g))assert.ok(existsSync(new URL(match[1],import.meta.url)));
assert.ok(!html.includes('800<span>円'),'Old tail-box price removed');
console.log(`PASS: 10 vendors, ${data.sources.length} sources; source integrity, price boundaries, volumetric threshold, invalid inputs, HTML targets.`);
